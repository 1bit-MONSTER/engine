"""Write tests/golden/host_gemm_i8_fixture.h — the known answer for q4nx_host_gemm_i8().

engine#1808: the kernel gate asks for "bit-exact against the host reference", but the only host arm the
forward offers is f32 (`q4nx_host_gemm_f32_padded`), and f32 cannot be bit-exact with an int8 x int4
device by construction. The integer arm (`q4nx_host_gemm_i8`) accumulates exactly, and this fixture is its
independent known answer: the expected int32 values are computed here, in Python, from the operands that
are also written out, so a C++ change that merely agrees with itself cannot pass the test.

    tools/host_gemm_i8_fixture.py > tests/golden/host_gemm_i8_fixture.h

Fixed seed, so the file is reproducible; K=128 (the smallest shape that reaches a whole 128-K group) and
N=4 columns, with activations across the quantiser's full [-127, 127] range and codes across [-8, 7].
"""
import random
import sys

SEED = 20261110
K, N = 128, 4


def main():
    rng = random.Random(SEED)
    a8 = [rng.randint(-127, 127) for _ in range(K)]
    codes = [[rng.randint(-8, 7) for _ in range(N)] for _ in range(K)]   # int4 value held in an int8
    expect = [sum(codes[k][n] * a8[k] for k in range(K)) for n in range(N)]
    w = sys.stdout.write
    w("// Copyright 2026 bong-water-water-bong\n")
    w("// SPDX-License-Identifier: Apache-2.0\n")
    w("//\n")
    w("// Licensed under the Apache License, Version 2.0 (the \"License\");\n")
    w("// you may not use this file except in compliance with the License.\n")
    w("// You may obtain a copy of the License at\n")
    w("//\n")
    w("//     http://www.apache.org/licenses/LICENSE-2.0\n")
    w("//\n")
    w("// Unless required by applicable law or agreed to in writing, software\n")
    w("// distributed under the License is distributed on an \"AS IS\" BASIS,\n")
    w("// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n")
    w("// See the License for the specific language governing permissions and\n")
    w("// limitations under the License.\n")
    w("//\n")
    w("// Generated by tools/host_gemm_i8_fixture.py -- do not edit. Known answer for\n")
    w("// tests/npu_host_gemm_i8_test.cpp: int8 x int4 -> int32, exact, no scales involved.\n")
    w("#pragma once\n#include <cstdint>\n\n")
    w(f"static constexpr int kHostI8K = {K};\nstatic constexpr int kHostI8N = {N};\n\n")
    w(f"static const int8_t kHostI8A[{K}] = {{{', '.join(str(v) for v in a8)}}};\n\n")
    w(f"static const int8_t kHostI8Codes[{K}][{N}] = {{\n")
    for k in range(K):
        w("    {%s},\n" % ", ".join(str(v) for v in codes[k]))
    w("};\n\n")
    w(f"static const int32_t kHostI8Expected[{N}] = {{{', '.join(str(v) for v in expect)}}};\n")


if __name__ == "__main__":
    main()
