// systemone_test: the d3 question/answer contract (npu/systemone.h) against fixtures generated by the
// PACK'S OWN d3_format.py, byte for byte.  No device, no model, no network: the fixture file is
// committed and carries the revision it came from.
#include "systemone.h"

#include <cmath>
#include <cstdio>
#include <fstream>
#include <nlohmann/json.hpp>
#include <string>
#include <vector>

using onebit::npu::d3::answer_of;
using onebit::npu::d3::candidate_codes;
using onebit::npu::d3::question_of;
using onebit::npu::d3::user_prompt;

namespace {

int failures = 0;
void check(bool ok, const std::string& what) {
    if (ok) return;
    ++failures;
    std::printf("FAIL %s\n", what.c_str());
}

bool close(double a, double b, double eps = 1e-6) { return std::fabs(a - b) <= eps; }

std::string escape(const std::string& s) {
    std::string out;
    for (char c : s) {
        if (c == '\n') out += "\\n";
        else if (c == '\t') out += "\\t";
        else out += c;
    }
    return out;
}

void test_prompt_golden(const std::string& fixture_path) {
    std::ifstream f(fixture_path);
    if (!f) {
        check(false, "cannot open " + fixture_path);
        return;
    }
    // ordered_json, not json: the fixture's key order is part of the contract (upstream preserves the
    // request's order), and nlohmann::json would sort it on the way in.
    const auto doc = nlohmann::ordered_json::parse(f);
    check(doc.contains("source") && doc["source"].is_string(), "the fixture names its upstream source");
    size_t checked = 0;
    for (const auto& c : doc.at("cases")) {
        const std::string name = c.at("name").get<std::string>();
        const auto& state = c.at("state");
        const auto q = question_of(c.at("question"));
        std::vector<std::string> codes = c.at("codes").get<std::vector<std::string>>();
        const std::string got = user_prompt(state, q, codes);
        const std::string want = c.at("expected_user_prompt").get<std::string>();
        checked++;
        if (got != want) {
            check(false, name + ": prompt differs from upstream\n  want: " + escape(want) + "\n  got:  " + escape(got));
        }
    }
    check(checked >= 9, "every fixture case was exercised (" + std::to_string(checked) + ")");
}

void test_question_rules() {
    // A choice needs a criteria object and at most 255 options.
    auto throws_with = [](const char* body, const char* needle) {
        try {
            question_of(nlohmann::ordered_json::parse(body));
        } catch (const std::exception& e) {
            return std::string(e.what()).find(needle) != std::string::npos;
        }
        return false;
    };
    check(throws_with(R"({"type": "choice"})", "criteria"), "a choice without criteria is refused");
    check(throws_with(R"({"type": "choice", "criteria": {}})", "at least one option"),
          "an empty choice is refused");
    check(throws_with(R"({"type": "box"})", "not served"), "a vision question kind is refused by name");
    check(throws_with(R"({})", "must name a type"), "a question without a type is refused");
    check(throws_with(R"({"type": "score", "criteria": ["only"]})", "2 to 10"),
          "a one-level score is refused");
    check(throws_with(R"({"type": "score", "criteria": ["a","b","c","d","e","f","g","h","i","j","k"]})", "2 to 10"),
          "an eleven-level score is refused");
    check(throws_with(R"({"type": "score", "criteria": ["a", "a"]})", "distinct"),
          "duplicate score levels are refused");
    check(throws_with(R"({"type": "score", "criteria": ["a", ""]})", "non-empty"),
          "an empty score level is refused");

    // noul is always the same two options, with the pack's fallback texts.
    const auto noul = question_of(nlohmann::ordered_json::parse(R"({"type": "noul"})"));
    check(noul.keys.size() == 2 && noul.keys[0] == "false" && noul.keys[1] == "true",
          "noul's options are false/true");
    check(noul.texts[0] == "No / false" && noul.texts[1] == "Yes / true", "noul's fallback texts are upstream's");
    // ... and a criteria text replaces them.
    const auto noul2 = question_of(nlohmann::ordered_json::parse(
        R"({"type": "noul", "criteria": {"false": "hold", "true": "ship"}})"));
    check(noul2.texts[0] == "hold" && noul2.texts[1] == "ship", "noul's criteria rename its options");

    // 255 codes is the cap; the 256th option is refused.
    nlohmann::ordered_json big = {{"type", "choice"}, {"criteria", nlohmann::ordered_json::object()}};
    for (int i = 0; i < 256; i++) big["criteria"]["k" + std::to_string(i)] = nullptr;
    bool refused = false;
    try {
        question_of(big);
    } catch (const std::exception& e) {
        refused = std::string(e.what()).find("255") != std::string::npos;
    }
    check(refused, "more than 255 options is refused");

    // The code list is d3's: one letter first, then two, capped at 255.
    const auto codes = candidate_codes();
    check(codes.size() == 255 && codes[0] == "A" && codes[25] == "Z" && codes[26] == "AA" && codes.back() == "IU",
          "candidate codes are A..Z then AA.. up to 255");
}

void test_answers() {
    const auto choice = question_of(nlohmann::ordered_json::parse(
        R"({"type": "choice", "criteria": {"a": null, "b": null}})"));
    const auto ans = answer_of(choice, {0.25f, 0.75f});
    check(ans["type"] == "choice" && ans["choice"] == "b", "a choice answers with its best option");
    check(close(ans["probabilities"]["a"].get<double>(), 0.25) &&
              close(ans["probabilities"]["b"].get<double>(), 0.75),
          "the probabilities are normalised in prompt order");
    const double even = 1.0;  // H = log 2 -> confidence 0
    check(close(ans["confidence"].get<double>(), even, 1e-9) == false, "a skewed choice has confidence above 0");
    check(ans["confidence"].get<double>() > 0.0 && ans["confidence"].get<double>() <= 1.0,
          "confidence is in [0, 1]");

    const auto tie = answer_of(choice, {1.0f, 1.0f});
    check(tie["choice"] == "a", "a tie keeps the first option, as upstream's strict > does");
    check(close(tie["confidence"].get<double>(), 0.0), "a flat distribution has confidence 0");

    const auto noul = question_of(nlohmann::ordered_json::parse(R"({"type": "noul"})"));
    const auto na = answer_of(noul, {0.1f, 0.9f});
    check(na["type"] == "noul" && close(na["noul"].get<double>(), 0.9), "noul answers with p(true)");

    const auto score = question_of(nlohmann::ordered_json::parse(
        R"({"type": "score", "criteria": ["bad", "ok", "great"]})"));
    const auto sa = answer_of(score, {0.0f, 1.0f, 0.0f});
    check(sa["type"] == "score" && close(sa["score"].get<double>(), 1.0),
          "score is the level index weighted by its probability");
    check(sa["probabilities"].size() == 3 && sa["probabilities"].contains("1") && sa["legend"]["1"] == "ok",
          "a score keys its probabilities and legend by level index, as upstream does");
    check(!sa["probabilities"].contains("ok") && !sa["legend"].contains("ok"),
          "a score does not key by the level text (upstream's keys are \"0\"..\"n-1\")");
    const auto mid = answer_of(score, {0.0f, 1.0f, 0.0f});
    check(close(mid["confidence"].get<double>(), 1.0), "one level taking everything is full confidence");

    // Refusals: wrong count, negative, all-zero.
    auto refuses = [](const onebit::npu::d3::Question& q, std::vector<float> p, const char* needle) {
        try {
            answer_of(q, p);
        } catch (const std::exception& e) {
            return std::string(e.what()).find(needle) != std::string::npos;
        }
        return false;
    };
    check(refuses(choice, {1.0f}, "probabilities"), "a probability per option is required");
    check(refuses(choice, {-1.0f, 2.0f}, "non-negative"), "a negative probability is refused");
    check(refuses(choice, {0.0f, 0.0f}, "sum to zero"), "an all-zero distribution is refused");
}

}  // namespace

int main(int argc, char** argv) {
    const std::string fixtures = argc > 1 ? argv[1] : "tests/golden/systemone/prompts.json";
    test_prompt_golden(fixtures);
    test_question_rules();
    test_answers();
    std::printf("%s\n", failures ? "FAILED" : "systemone: ok");
    return failures ? 1 : 0;
}
