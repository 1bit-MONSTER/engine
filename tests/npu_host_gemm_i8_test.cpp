// npu_host_gemm_i8_test: the known answer for the integer host arm (engine#1808).
//
// The gate for a kernel family asks for "bit-exact against the host reference". The only host arm the
// forward offers is f32, and f32 cannot be bit-exact with an int8 x int4 device by construction, so the
// comparison can only ever produce a quality number. `q4nx_host_gemm_i8()` is the missing arm: exact int32
// accumulation of the same operands the kernel gets.
//
// This test is a *known answer*, not a re-implementation: the fixture in tests/golden/ was generated by an
// independent Python computation (tools/host_gemm_i8_fixture.py) with a fixed seed, so a change that
// "agrees with itself" cannot pass. Three arms:
//   1. the fixture: K=128, N=4, int8 activations and int4 codes, expected int32 per column;
//   2. the int4 range: every code in the fixture lies in [-8, 7] (a code outside it would mean the caller
//      is handing us a q4_1 byte instead of a code, which is the mistake the whole gate exists to catch);
//   3. the edge: an activation of -128 (outside the quantiser's range, inside int8) must still accumulate
//      exactly rather than saturate at the int32 level -- the product bound is 128 * 8 * K, which for the
//      largest K in use (14336) is 1.47e7, far inside int32, so a saturation here would be a real bug.

#include "q4nx_pack.h"

#include <cstdio>
#include <cstring>
#include <vector>
#include <cmath>
#include <algorithm>

#include "golden/host_gemm_i8_fixture.h"

static int failures = 0;

static void check(bool ok, const char* what) {
    std::printf("%s   %s\n", ok ? "ok  " : "FAIL", what);
    if (!ok) failures++;
}

int main() {
    // 1. the recorded known answer
    int32_t got[kHostI8N] = {0, 0, 0, 0};
    q4nx_host_gemm_i8(kHostI8A, kHostI8K, &kHostI8Codes[0][0], kHostI8N, got);
    bool same = true;
    for (int n = 0; n < kHostI8N; n++) {
        if (got[n] != kHostI8Expected[n]) {
            std::printf("     column %d: got %d, expected %d\n", n, (int)got[n], (int)kHostI8Expected[n]);
            same = false;
        }
    }
    check(same, "int8 x int4 -> int32 matches the independent Python fixture, all 4 columns");

    // 2. the fixture only carries int4 codes
    bool in_range = true;
    for (int k = 0; k < kHostI8K && in_range; k++)
        for (int n = 0; n < kHostI8N; n++)
            if (kHostI8Codes[k][n] < -8 || kHostI8Codes[k][n] > 7) in_range = false;
    check(in_range, "every weight code is an int4 value in [-8, 7]");

    // 3. the int32 edge: a naive int8 multiply would overflow at 128 * 127, this must not
    const int K = 256;
    static int8_t a8[256];
    static int8_t codes[256 * 2];
    for (int k = 0; k < K; k++) { a8[k] = (k == 0) ? -128 : 127; codes[k * 2] = -8; codes[k * 2 + 1] = 7; }
    int32_t edge[2] = {0, 0};
    q4nx_host_gemm_i8(a8, K, codes, 2, edge);
    // column 0: -8 * (-128) + -8 * 127 * 255 = 1024 - 259080 = -258056
    // column 1:  7 * (-128) +  7 * 127 * 255 = -896 + 226695 = 225799
    check(edge[0] == -258056 && edge[1] == 225799,
          "a -128 activation accumulates exactly (no int8 intermediate, no int32 saturation)");

    // 4. the whole-GEMM arm the gate switches on: quantise both sides here, accumulate exactly, and check
    //    the two properties that make the comparison meaningful -- the per-128-K group boundary is honoured
    //    (a K of 130 must not fold the last two rows into the first group's scale) and int4 codes stay in
    //    [-8, 7] so an out-of-range code cannot silently wrap.
    {
        const int KK = 130, NN = 3, MM = 2;
        std::vector<float> A((size_t)MM * KK), B((size_t)KK * NN);
        for (int m = 0; m < MM; m++)
            for (int k = 0; k < KK; k++) A[(size_t)m * KK + k] = (float)((k * 7 + m * 3) % 11) - 5.0f;
        for (int k = 0; k < KK; k++)
            for (int n = 0; n < NN; n++) B[(size_t)k * NN + n] = (float)((k * 5 + n * 13) % 17) / 3.0f;
        std::vector<int32_t> out((size_t)MM * NN, 0);
        q4nx_host_gemm_i8_from_f32(A.data(), KK, MM, KK, NN, B.data(), out.data());
        // independent computation in long double, from the same quantisation rule
        bool ok = true;
        for (int m = 0; m < MM && ok; m++) {
            for (int n = 0; n < NN && ok; n++) {
                double want = 0;
                for (int g = 0; g < 2; g++) {                       // 128 + 2 rows = two groups
                    const int k0 = g * 128, k1 = (k0 + 128 < KK) ? k0 + 128 : KK;
                    double amax = 0;
                    for (int k = k0; k < k1; k++) amax = std::max(amax, std::fabs((double)B[(size_t)k * NN + n]));
                    if (amax < 1e-12) amax = 1;
                    const double tis = 127.0 / amax;
                    for (int k = k0; k < k1; k++) {
                        int q = (int)std::round((double)B[(size_t)k * NN + n] * tis);
                        q = q > 7 ? 7 : (q < -8 ? -8 : q);
                        int aq = (int)std::round((double)A[(size_t)m * KK + k] * 127.0);
                        aq = aq > 127 ? 127 : (aq < -127 ? -127 : aq);
                        want += (double)q * (double)aq;
                    }
                }
                if ((double)out[(size_t)m * NN + n] != want) {
                    std::printf("     m=%d n=%d: got %d, want %.0f\n", m, n, (int)out[(size_t)m * NN + n], want);
                    ok = false;
                }
            }
        }
        check(ok, "whole-GEMM i8 arm: exact int32, 128-K group boundary respected at K=130");
    }

    if (failures) { std::fprintf(stderr, "%d check(s) failed\n", failures); return 1; }
    std::printf("all npu_host_gemm_i8 checks passed\n");
    return 0;
}
