// systemone_route_test: the HTTP half of the d3 decision route (app/npu_systemone.h) -- the request
// envelope, the prompt wrapper and the reply shape -- with no model, no device and no network.
//
// The prompt wrapper is checked against the same committed fixtures the contract test uses
// (tests/golden/systemone/prompts.json, generated by the pack's own d3_format.py), by wrapping each
// expected user turn in the chat template's bytes. That is the part a "reuse chatml()" shortcut would
// silently get wrong: the assistant turn opens with an EMPTY think block, and those bytes are input.
#include "npu_systemone.h"

#include <cstdio>
#include <fstream>
#include <nlohmann/json.hpp>
#include <string>
#include <vector>

using nlohmann::ordered_json;
using onebit::npu::SystemOneParsed;
using onebit::npu::SystemOneRefusal;
using onebit::npu::systemone_length_message;
using onebit::npu::systemone_models;
using onebit::npu::systemone_prompt;
using onebit::npu::systemone_question_error;
using onebit::npu::systemone_reply;
using onebit::npu::systemone_request_of;

namespace {

int failures = 0;
void check(bool ok, const std::string& what) {
    if (ok) return;
    ++failures;
    std::printf("FAIL %s\n", what.c_str());
}

// The refusal a body earns, or "" when it is accepted.
std::string refusal(const std::string& body) {
    try {
        systemone_request_of(ordered_json::parse(body));
        return "";
    } catch (const SystemOneRefusal& ex) {
        return ex.what();
    }
}

bool contains(const std::string& hay, const std::string& needle) {
    return hay.find(needle) != std::string::npos;
}

void test_request_envelope() {
    // The whole-request refusals: each names the field, because a d3 request that is silently
    // reinterpreted is a wrong answer, not a 400.
    check(contains(refusal("[]"), "expected a JSON object"), "a non-object body is refused");
    check(contains(refusal("{}"), "questions is required"), "a body without questions is refused");
    check(contains(refusal(R"({"questions": []})"), "questions is required"),
          "a questions LIST is refused: the ids are the keys of answers");
    check(contains(refusal(R"({"questions": {}})"), "questions is required"), "an empty questions object is refused");
    check(contains(refusal(R"({"questions": {"a": {"type": "choice"}, "": {"type": "choice"}}})"),
          "nonempty strings"),
          "an empty question id is refused");
    const std::string unknown = refusal(R"({"questions":{"a":{"type":"noul"}},"temprature":0.2})");
    check(contains(unknown, "temprature not understood"), "an unknown field is refused by name");
    check(contains(unknown, "state, questions, model"), "the refusal lists the accepted fields");
    check(contains(refusal(R"({"questions":{"a":{"type":"noul"}},"images":["data:image/png;base64,AA"]})"),
          "images: this build serves the text path only"),
          "images are refused by name, not ignored");
    check(contains(refusal(R"({"questions":{"a":{"type":"noul"}},"videos":[]})"), "videos:"),
          "videos are refused by name, not ignored");

    // `model` is accepted and ignored (upstream accepts it; the reply names the served model).
    const SystemOneParsed m = systemone_request_of(
        ordered_json::parse(R"({"questions":{"a":{"type":"noul"}},"model":"vllm-sr/d3-lite"})"));
    check(m.questions.size() == 1 && m.invalid.empty(), "model is accepted and ignored");
    check(m.state.is_null(), "state is optional and defaults to null");
}

void test_questions_and_invalid() {
    // A malformed question is collected per id, so one reply can name every bad one -- and valid
    // questions are still parsed (the caller answers 422 and runs nothing).
    const ordered_json body = ordered_json::parse(R"({"state":{"x":1},
        "questions":{"route":{"type":"choice","criteria":{"fast":null,"cheap":"cheap one"}},
                     "bad1":{"type":"choice","criteria":{}},
                     "yes":{"type":"noul"},
                     "bad2":{"type":"bogus"}}})");
    const SystemOneParsed p = systemone_request_of(body);
    check(p.questions.size() == 2, "two valid questions parsed (" + std::to_string(p.questions.size()) + ")");
    check(p.questions.size() == 2 && p.questions[0].id == "route" && p.questions[1].id == "yes",
          "questions keep request order and their ids");
    check(p.invalid.size() == 2, "two malformed questions collected (" + std::to_string(p.invalid.size()) + ")");
    check(p.invalid.size() == 2 && p.invalid[0].first == "bad1" && p.invalid[1].first == "bad2",
          "invalid questions keep request order");
    check(p.invalid.size() == 2 && contains(p.invalid[0].second, "at least one option"),
          "an empty choice criteria says why: " + (p.invalid.empty() ? std::string() : p.invalid[0].second));
    check(p.invalid.size() == 2 && contains(p.invalid[1].second, "is not served"),
          "an unknown question type says why");
    // The id order of the request itself is preserved even when the middle one is invalid.
    check(p.questions.size() == 2 && p.questions[0].question.keys.size() == 2, "the valid choice has two options");
}

void test_prompt_bytes(const std::string& fixture_path) {
    std::ifstream f(fixture_path);
    if (!f) {
        check(false, "cannot open " + fixture_path);
        return;
    }
    const auto doc = ordered_json::parse(f);
    size_t checked = 0;
    for (const auto& c : doc.at("cases")) {
        const std::string name = c.at("name").get<std::string>();
        const ordered_json state = c.at("state");
        const auto q = onebit::npu::d3::question_of(c.at("question"));
        const std::vector<std::string> codes = c.at("codes").get<std::vector<std::string>>();
        // The user turn is already byte-compared upstream; here it is wrapped in the chat template,
        // so what this checks is the wrapper -- including the empty think block that opens the
        // assistant turn (d3_format._chat_text with enable_thinking=False).
        const std::string want = "<|im_start|>system\n" +
                                 std::string(onebit::npu::d3::kSystemPrompt) + "<|im_end|>\n" +
                                 "<|im_start|>user\n" + c.at("expected_user_prompt").get<std::string>() +
                                 "<|im_end|>\n" + "<|im_start|>assistant\n<think>\n\n</think>\n\n";
        const std::string got = systemone_prompt(state, q, codes);
        checked++;
        if (got != want) check(false, name + ": prompt wrapper differs from the pack's chat template");
    }
    check(checked >= 9, "every fixture case got a wrapped prompt (" + std::to_string(checked) + ")");
    // The wrapper is not our ChatML: that one opens no think block, so the two cannot be swapped.
    const std::string one = systemone_prompt(ordered_json(nullptr),
                                             onebit::npu::d3::question_of(ordered_json::parse(
                                                 R"({"type":"noul"})")),
                                             {"A", "B", "C"});
    check(contains(one, "<|im_start|>assistant\n<think>\n\n</think>\n\n"),
          "the assistant turn opens with the empty think block");
    check(!contains(one, "<|im_end|>\n<|im_start|>assistant\n<|im_end|>"), "not the plain ChatML wrapper");
}

void test_reply_shape() {
    // {"model", "answers", "usage"}: the envelope vLLM Semantic Router reads, `answers` keyed by the
    // caller's question ids in request order, and no output tokens because nothing is generated.
    ordered_json answers = ordered_json::object();
    answers["route"] = ordered_json{{"type", "choice"}, {"choice", "fast"}};
    answers["yes"] = ordered_json{{"type", "noul"}, {"noul", 0.75}};
    const ordered_json reply = systemone_reply("d3-lite", answers, 217);
    const std::string text = reply.dump();
    check(contains(text, R"("model":"d3-lite")"), "the reply names the served model");
    check(contains(text, R"("output_tokens":0)"), "a decision generates no tokens");
    check(contains(text, R"("input_tokens":217)"), "input_tokens is the summed prompt length");
    check(text.find(R"("route")") < text.find(R"("yes")"), "answers keep request order");
    check(contains(text, R"("answers":{)"), "answers is an object keyed by question id");

    // A question that cannot be answered: {"type", "error", "message"}, with a null type when the
    // question itself named none (upstream's per-question error entries).
    const nlohmann::json bad = systemone_question_error("choice", "max_length_exceeded", "too long");
    check(bad.at("type") == "choice" && bad.at("error") == "max_length_exceeded" && bad.at("message") == "too long",
          "an unanswered question is {type, error, message}");
    check(systemone_question_error("", "invalid_question", "x").at("type").is_null(),
          "an untyped question reports type null rather than empty");

    // The limit message states both numbers and that nothing was truncated -- the property the issue
    // asks for, since a silently truncated prompt would be a different question.
    const std::string len = systemone_length_message(40001, 32768);
    check(contains(len, "40001 tokens") && contains(len, "32768 tokens"), "the limit message carries both counts");
    check(contains(len, "nothing was truncated"), "the limit message says nothing was truncated");

    // The model list: one entry, text only, with the same limit the request check uses.
    const ordered_json models = systemone_models("d3-lite", 32768);
    const std::string mtext = models.dump();
    check(contains(mtext, R"("models":[{)"), "the list is {\"models\": [...]}");
    check(contains(mtext, R"("modalities":["text"])"), "the text path advertises text only");
    check(contains(mtext, R"("max_input_tokens":32768)"), "the list carries the input limit");
    check(contains(mtext, "Typed decisions with a probability for every option"), "upstream's description");
}

}  // namespace

int main(int argc, char** argv) {
    test_request_envelope();
    test_questions_and_invalid();
    test_reply_shape();
    if (argc > 1)
        test_prompt_bytes(argv[1]);
    else
        check(false, "usage: systemone_route_test <tests/golden/systemone/prompts.json>");
    std::printf("%s\n", failures ? "FAILED" : "systemone_route: ok");
    return failures ? 1 : 0;
}
