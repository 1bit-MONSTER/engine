# g3-probe.sh <iso> <work-dir> [--kver <kver>] [--cert <pem>] [--require-mok]
#
# Gate G3 of docs/os-v3-live-puppy-eval.md, artifact half: the image carries OUR kernel, that kernel image is
# SIGNED, and `amdxdna` and `ec_su_axb35` are in it, built for THAT kernel and signed. Reads the ISO and the
# zdrv inside it, so it measures the artifact and not the build tree beside it.
#
# <iso>       the built image (upup64r-26.04.iso)
# <work-dir>  where the extracted kernel and zdrv land
# --kver      the expected kernel release string; without it any *-1bit-* release is accepted and printed
# --cert      verify the kernel image's signature against this certificate (the machine's enrolled MOK). An
#             unsigned kernel image is a FAIL either way; with --cert, a signature by another key is too.
# --require-mok  a module signed by anything but an enrolled MOK is a FAIL instead of a warning (the
#             release gate passes this: U4 wants Secure Boot ON). Measured 2026-11-02 - the ISO built before
#             this probe existed carries amdxdna.ko signed by "Build time autogenerated kernel key", the
#             module build's ephemeral key, which loads on the box only because lockdown is `none`
#
# Why the kernel row exists at all: this probe checked the modules and never the kernel image, so on 2 Nov
# the board loaded shim -> Canonical GRUB and then stopped with `error: bad shim lock signature / you need to
# load the kernel first` on a `vmlinuz` that had never been signed. The VM rows could not see it either (a
# `-kernel` boot verifies nothing), so both halves of that hole are closed: this row, and vm-check.sh's
# Secure Boot boot. mk-huge-kernel.sh refuses an unsigned image as well - three places, one defect.
#
# What this does NOT prove, and nothing here may imply it: that the kernel BOOTS, and that the devices are
# on the board. `uname -r`, `amdgpu` loading and the EC/fan devices need a booted machine - g2-probe.sh
# (VM) and the board rows (TPUPPY-RELEASE U5). This gate is the one that fails loudly when a kernel bump
# leaves the out-of-tree modules behind, which is silent in every other check: mk-huge-kernel.sh asserts
# the modules it is GIVEN, and an empty updates/ passes it without a word (measured 2026-11-02: the OOT
# modules live in /lib/modules/<kver>/updates/ and are valid for exactly one kernel).
#
# Exit 0 when every check passes, 1 when a check fails (G3 red), 2 on a usage or tool error.
set -uo pipefail
prog=g3-probe
usage() { sed -n '/^# g3-probe.sh/,/^# Exit/p' "$0" | sed 's/^# \{0,1\}//'; }
fail=0
want=""
cert=""
want_sv=""
require_mok=0
bad() { printf '  FAIL %s\n' "$*"; fail=$((fail + 1)); }
ok() { printf '  ok   %s\n' "$*"; }
warn() { printf '  warn %s\n' "$*"; }

[ $# -ge 2 ] || { usage >&2; exit 2; }
iso=$(cd "$(dirname "$1")" 2>/dev/null && pwd)/$(basename "$1")
work=$2
shift 2
while [ $# -gt 0 ]; do
    case $1 in
    --kver) want=${2:-}; shift 2 || { usage >&2; exit 2; } ;;
    --cert) cert=${2:-}; shift 2 || { usage >&2; exit 2; } ;;
    --srcversion) want_sv=${2:-}; shift 2 || { usage >&2; exit 2; } ;;
    --require-mok) require_mok=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) printf '%s: unknown option %s\n' "$prog" "$1" >&2; exit 2 ;;
    esac
done
[ -f "$iso" ] || { echo "$prog: no such image: $iso" >&2; exit 2; }
for t in xorriso unsquashfs file modinfo grep sbverify; do
    command -v "$t" > /dev/null || { echo "$prog: $t is missing" >&2; exit 2; }
done
[ -z "$cert" ] || [ -r "$cert" ] || { echo "$prog: cannot read the certificate $cert" >&2; exit 2; }
mkdir -p "$work" || exit 2
work=$(cd "$work" && pwd)

echo "== $iso"
# the kernel: `file` reads the release string out of the setup header, which is what an appliance sees as
# `uname -r` (mk-huge-kernel.sh checks the same string before packaging, for the same reason)
# The work dir is a CACHE (vmlinuz, zdrv.sfs, the unpacked module tree) and it was not keyed to the artifact: running
# this probe twice into the same dir graded the FIRST image's modules on the second run. Measured on c26 - an ISO whose
# zdrv carries srcversion EE1F36A2… came back `FAIL amdxdna.ko srcversion is 'BBE1E5F0…' (a stale module)`, because the
# zdrv.sfs and the extracted tree were the previous cut's. Reusing a work dir is the documented way to re-run, so the
# cache has to prove it belongs to THIS image: a different sha256 wipes it, and the verdict is then about this artifact.
sum=$(sha256sum "$iso" 2> /dev/null | cut -d' ' -f1)
if [ -n "$sum" ] && [ "$(cat "$work/.artifact-sha256" 2> /dev/null)" != "$sum" ]; then
    rm -rf "$work/vmlinuz" "$work/zdrv.sfs" "$work/zdrv"
    printf '%s\n' "$sum" > "$work/.artifact-sha256" 2> /dev/null
    echo "  cache: new artifact (${sum%"${sum#????????}"}…), work dir cleared"
fi
[ -s "$work/vmlinuz" ] || xorriso -osirrox on -indev "$iso" -extract /vmlinuz "$work/vmlinuz" > /dev/null 2>&1
[ -s "$work/vmlinuz" ] || { echo "$prog: cannot extract /vmlinuz from the image" >&2; exit 2; }
kver=$(file -b "$work/vmlinuz" | sed -n 's/.*version \([^ ]*\) .*/\1/p' | head -n 1)
[ -n "$kver" ] || { echo "$prog: cannot read a release string out of /vmlinuz" >&2; exit 2; }
echo "  kernel: $kver"
if [ -n "$want" ]; then
    [ "$kver" = "$want" ] && ok "release string is $want" || bad "release string is $kver, expected $want"
else
    # Two spellings are ours: LOCALVERSION=-1bit-perfopt+ on the 7.3 kernel (a `-1bit-` infix) and
    # LOCALVERSION=-1bit on the 7.4 one, where the string ENDS with `-1bit`. The pattern only had the infix
    # form, so the very first 7.4 image (cycle 22, 2026-11-04) read as "not our kernel" here whenever the run
    # did not pass --kver - a correct artifact failed a gate for its naming.
    case $kver in *-1bit|*-1bit-*) ok "release string carries our kernel ($kver)" ;; *) bad "not our kernel: $kver" ;; esac
fi
case $kver in *++*) bad "the release string has a doubled '+' ($kver): the build tree added to LOCALVERSION" ;; esac

# the kernel IMAGE's own signature, which is what GRUB's shim_lock verifier checks under Secure Boot. This
# is the check whose absence shipped an unbootable stick on 2 Nov: "No signature table present" on the
# image, while every module in the zdrv was properly MOK-signed and this probe passed.
ksig=$(sbverify --list "$work/vmlinuz" 2> /dev/null | sed -n 's/^ - //p' | head -n 1)
if [ -z "$ksig" ]; then
    bad "/vmlinuz is UNSIGNED - Secure Boot's GRUB refuses it (board, 2 Nov: 'bad shim lock signature'); sign-vmlinuz.sh"
elif [ -n "$cert" ]; then
    if sbverify --cert "$cert" "$work/vmlinuz" > /dev/null 2>&1; then
        ok "/vmlinuz verifies against $cert"
    else
        bad "/vmlinuz is signed by '$ksig', which does not verify against $cert"
    fi
else
    ok "/vmlinuz signed by $ksig (pass --cert to require the enrolled MOK)"
fi

# the zdrv: Puppy's module SFS, mounted and unioned over / at boot, so this is where /lib/modules/<kver>
# comes from on the appliance
zdrv=$(xorriso -osirrox on -indev "$iso" -find / -name 'zdrv*.sfs' 2> /dev/null | tr -d "'" | head -n 1 | sed 's/^\/\?//')
[ -n "$zdrv" ] || { echo "$prog: no zdrv*.sfs in the image (the modules SFS is what carries /lib/modules)" >&2; exit 2; }
[ -s "$work/zdrv.sfs" ] || xorriso -osirrox on -indev "$iso" -extract "/$zdrv" "$work/zdrv.sfs" > /dev/null 2>&1
[ -s "$work/zdrv.sfs" ] || { echo "$prog: cannot extract /$zdrv from the image" >&2; exit 2; }
echo "  zdrv: /$zdrv ($(stat -c %s "$work/zdrv.sfs") B)"
root=$work/zdrv
# Ubuntu 26.04 is usrmerged and the zdrv carries usr/lib/modules with a `lib -> usr/lib` link beside it
# (mk-huge-kernel.sh's ZDRV_LIBROOT), so both spellings are extracted and whichever exists is used:
# unsquashfs does not follow that symlink, so asking for 'lib/modules' alone extracts nothing and every
# row below then fails on a correct zdrv - measured on cycle 8's image.
if [ ! -d "$root/lib/modules/$kver" ] && [ ! -d "$root/usr/lib/modules/$kver" ]; then
    rm -rf "$root"
    unsquashfs -q -f -n -d "$root" "$work/zdrv.sfs" 'lib/modules' 'lib/firmware' 'usr/lib/modules' \
        'usr/lib/firmware' > /dev/null 2>&1
fi
modsdir=$root/lib/modules/$kver
[ -d "$modsdir" ] || modsdir=$root/usr/lib/modules/$kver
fwdir=$root/lib/firmware
[ -d "$fwdir" ] || fwdir=$root/usr/lib/firmware
[ -d "$modsdir" ] && ok "zdrv carries ${modsdir#"$root"} (the module tree the appliance mounts)" ||
    bad "zdrv has no modules/$kver (a kernel bump that left the zdrv behind)"

# the two out-of-tree modules are the difference between an appliance with fans and an NPU and one without.
# A kernel that ships its own `amdxdna` in drivers/accel AND a pinned one in updates/ has TWO files with the
# same name; depmod resolves updates/ first, so that is the one the appliance loads and the one this checks
# (the other is reported, not silently ignored).
for m in amdxdna ec_su_axb35; do
    ko=$(find "$modsdir" -name "$m.ko*" 2> /dev/null |
        awk -v m="/updates/" '{ if (index($0, m)) print 0, $0; else print 1, $0 }' | sort | head -n 1 | cut -d' ' -f2-)
    others=$(find "$modsdir" -name "$m.ko*" 2> /dev/null | grep -v -F "$ko" | tr '\n' ' ')
    if [ -z "$ko" ]; then
        bad "$m.ko is not in the zdrv for $kver"
        continue
    fi
    [ -z "$others" ] || ok "$m: depmod resolves $ko (also present: $others)"
    magic=$(modinfo -F vermagic "$ko" 2> /dev/null | awk '{print $1}')
    signer=$(modinfo -F signer "$ko" 2> /dev/null)
    [ "$magic" = "$kver" ] && ok "$m.ko vermagic $magic" ||
        bad "$m.ko vermagic is '${magic:-<unreadable>}', the zdrv kernel is $kver"
    # srcversion names the SOURCE the module was built from (it is not the kernel version): a vermagic and a MOK
    # signature pass for every module we have ever built, so "c25 must carry patch 0008, not 0007" cannot be answered
    # by presence at all. --srcversion makes the artifact answer it, and a mismatch is a FAIL by construction.
    sv=$(modinfo -F srcversion "$ko" 2> /dev/null)
    if [ "$m" = amdxdna ] && [ -n "$want_sv" ]; then
        [ "$sv" = "$want_sv" ] && ok "amdxdna.ko srcversion $sv (the source this cut was built from)" ||
            bad "amdxdna.ko srcversion is '${sv:-<none>}', this cut must carry $want_sv (a stale module)"
    else
        ok "$m.ko srcversion ${sv:-<none>}"
    fi
    case $signer in
    *"Secure Boot"*) ok "$m.ko signed by $signer" ;;
    "") bad "$m.ko is unsigned (Secure Boot refuses it at load)" ;;
    *)
        if [ "$require_mok" -eq 1 ]; then
            bad "$m.ko is signed by '$signer', not an enrolled MOK: under Secure Boot it loads only while lockdown is none"
        else
            warn "$m.ko is signed by '$signer', not an enrolled MOK (pass --require-mok to make that a failure)"
        fi
        ;;
    esac
done

# the firmware the appliance's GPU and NPU need, at its real path inside the zdrv
for fw in amdgpu amdnpu; do
    [ -d "$fwdir/$fw" ] && ok "/lib/firmware/$fw present" || bad "/lib/firmware/$fw missing from the zdrv"
done

n=$(find "$modsdir" -name '*.ko*' 2> /dev/null | wc -l)
echo "  modules in the zdrv: $n"
echo "== G3 (artifact half): $([ "$fail" -eq 0 ] && echo 'every check passed' || echo "$fail check(s) failed")"
echo "   not measured here: that it boots (g2-probe.sh) and that the devices are on the board (U5)"
[ "$fail" -eq 0 ] || exit 1
