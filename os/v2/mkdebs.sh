# mkdebs.sh <engine-stage> <lemonade-prefix> <version> <out-dir> [archive-keyring.gpg]
#
# Builds the appliance's packages from what a release build already produced - no binary is rebuilt
# here, dpkg-deb only wraps it:
#
#   1bit-engine      the engine, its llama-server and libraries, the sealed NPU kernel sets, the
#                    two commands that prove a boot                -> /opt/1bit
#   1bit-lemonade    our build of Lemonade Server (lemond, CLI, web app)  -> /opt/lemonade
#   1bit-appliance   the meta/config package: units, banner, first boot, apt source
#   1bit-archive-keyring  the public half of the key that signs 1bit.gg/apt
#   1bit-openwebui  the optional chat front end (units, console line, no container runtime:
#                    engine#594) - in the repository, installed by nobody, apt-installed on request
#
# With KERNEL_STAGE=<dir> set it also builds the three packages that only a box needs, from the
# release kernel build as it sits on the build machine (<dir>/boot/vmlinuz-<kver>, System.map-<kver>,
# config-<kver> and <dir>/lib/modules/<kver>/):
#
#   1bit-kernel-image-<kver>    vmlinuz + System.map + config, initramfs generated by its postinst
#   1bit-kernel-modules-<kver>  every module for <kver> (amdgpu, amdxdna, the board's EC driver) and
#                               the EC driver's source under /usr/src/1bit-ec-<ver>
#   1bit-ryzenadj               built here from os/licenses/ryzenadj/src (v0.19.0, LGPL-3.0),
#                               with its source beside it: the 90 W SMU cap needs it
#
# <engine-stage> is either the release tarball (1bit-<ver>-linux-x86_64.tar.zst from
# scripts/package-linux.sh) or an unpacked stage directory; <lemonade-prefix> is a build-lemonade.sh
# prefix (bin/lemond, bin/lemonade, bin/resources). <version> is the release tag, with or without the
# leading v: v2026.43 becomes 2026.43-1.
set -euo pipefail
[ $# -ge 4 ] || { sed -n '22,45p' "$0"; exit 2; }
stage_in=$1 lemon=$2 version=${3#v} out=$4 keyring=${5:-} kstage=${KERNEL_STAGE:-} kver=
here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$here/../.." && pwd)
debver="$version-1"
[ -n "$version" ] || { echo "mkdebs: empty version"; exit 2; }
[ -x "$lemon/bin/lemond" ] || { echo "mkdebs: no $lemon/bin/lemond (a build-lemonade.sh prefix)"; exit 2; }
mkdir -p "$out"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# --- the kernel: only a box needs these, so a VM/rootfs build runs without a stage at all ----------
# The version is read here and not where the packages are built, because 1bit-appliance depends on the
# three kernel packages by name and is packaged earlier in this script.
if [ -n "$kstage" ]; then
    kmods=$(ls -d "$kstage"/lib/modules/*/ 2>/dev/null | head -1)
    [ -n "$kmods" ] || { echo "mkdebs: $kstage carries no lib/modules/<kver>"; exit 2; }
    kver=$(basename "$kmods")
    for f in vmlinuz System.map config; do
        [ -f "$kstage/boot/$f-$kver" ] || { echo "mkdebs: $kstage carries no boot/$f-$kver"; exit 2; }
    done
    # the EC driver is what gives the box fan control, and Secure Boot only loads it signed: check it
    # against the kernel it was built for here, so a wrong pair fails the package build, not the boot
    ec=$kstage/lib/modules/$kver/updates/ec_su_axb35.ko
    [ -f "$ec" ] || { echo "mkdebs: no ec_su_axb35.ko in $kstage for $kver"; exit 2; }
    [ "$(modinfo -F vermagic "$ec" 2>/dev/null | cut -d' ' -f1)" = "$kver" ] || {
        echo "mkdebs: ec_su_axb35.ko is not built for $kver"; exit 1; }
    [ -n "$(modinfo -F signer "$ec" 2>/dev/null)" ] || {
        echo "mkdebs: ec_su_axb35.ko is unsigned: Secure Boot would refuse it"; exit 1; }
    echo "== kernel: $kver, $(du -sh "$kstage/lib/modules/$kver" | cut -f1) of modules, EC driver signed by '$(modinfo -F signer "$ec" | cut -d: -f2)'"
fi

# --- the engine stage: a tarball or a directory, never a fresh build --------------------------------
case "$stage_in" in
    *.tar.zst)
        mkdir -p "$work/stage"
        tar --zstd -xf "$stage_in" -C "$work/stage"
        stage=$(find "$work/stage" -maxdepth 1 -mindepth 1 -type d | head -1)
        ;;
    *)
        # a build directory: take the same surface scripts/package-linux.sh packs, not the build tree -
        # the tree carries objects and CMakeFiles that have no business in a package (1.3 GB vs ~150 MB)
        stage=$work/stage
        mkdir -p "$stage"
        cp -a "$stage_in/1bit" "$stage/"
        put() {   # <rel dir> <programs ...>: those programs plus every shared library beside them
            local rel=$1 f; shift
            [ -d "$stage_in/$rel" ] || return 0
            mkdir -p "$stage/$rel"
            for f in "$@"; do [ -f "$stage_in/$rel/$f" ] && cp -a "$stage_in/$rel/$f" "$stage/$rel/"; done
            find "$stage_in/$rel" -maxdepth 1 \( -name '*.so' -o -name '*.so.*' \) -exec cp -a {} "$stage/$rel/" \;
        }
        put hrx/llama/bin llama-server llama-bench
        put ds4/hip ds4-server ds4 ds4-bench
        # the sealed NPU sets: the artifact surface only (layout.json + layer1_*/layer1.elf)
        if [ -d "$stage_in/npu/kernels" ]; then
            mkdir -p "$stage/npu/kernels"
            for set in "$stage_in"/npu/kernels/*/; do
                sn=$(basename "$set")
                [ -f "$set/layout.json" ] || continue
                mkdir -p "$stage/npu/kernels/$sn"
                cp -a "$set/layout.json" "$stage/npu/kernels/$sn/"
                for layer in "$set"/layer1_*/; do
                    [ -f "$layer/layer1.elf" ] || continue
                    mkdir -p "$stage/npu/kernels/$sn/$(basename "$layer")"
                    cp -a "$layer/layer1.elf" "$stage/npu/kernels/$sn/$(basename "$layer")/"
                done
            done
        fi
        for d in scripts tools; do [ -d "$stage_in/$d" ] && cp -a "$stage_in/$d" "$stage/"; done
        echo "   stage: $(du -sh "$stage" | cut -f1) from $stage_in (1bit, llama-server, ds4, npu sets, scripts)"
        ;;
esac
[ -x "$stage/1bit" ] || { echo "mkdebs: $stage has no 1bit binary"; exit 2; }
engine_version=$("$stage/1bit" version 2>/dev/null | head -1)
engine_version=${engine_version:-unknown}

# a new package tree, with the Apache/Apache-2.0 notice files the release carries. @KVER@ is the
# kernel version for the three packages whose names carry it (Debian's own linux-image-<kver> rule:
# two kernels can be installed at once, which is what makes the previous one the rollback)
newpkg() {   # <name> -> sets $p
    p="$work/pkg/$1"
    mkdir -p "$p/DEBIAN"
    sed -e "s/@VERSION@/$debver/g" -e "s/@KVER@/$kver/g" "$here/debian/$1/control" > "$p/DEBIAN/control"
    chmod 644 "$p/DEBIAN/control"
}
# the file name apt expects to find in the pool: Package_Version_Arch.deb, read back out of the
# control file, so a package whose name carries the kernel version needs no second guess
builddeb() {
    local name
    name=$(sed -n 's/^Package: //p' "$p/DEBIAN/control")
    dpkg-deb --build --root-owner-group "$p" "$out/${name}_${debver}_amd64.deb" >/dev/null
}
# and the maintainer scripts, if that package has any
withscripts() {   # <name>
    local f
    for f in "$here/debian/$1"/{postinst,preinst,prerm,postrm,conffiles}; do
        [ -e "$f" ] || continue
        sed -e "s/@VERSION@/$debver/g" -e "s/@KVER@/$kver/g" "$f" > "$p/DEBIAN/$(basename "$f")"
        chmod 755 "$p/DEBIAN/$(basename "$f")"
    done
}
doc() {   # <pkgdir> <name>: licence files a package must carry
    local d=$1/usr/share/doc/$2
    mkdir -p "$d"
    for f in LICENSE NOTICE LICENSE-BINARY NOTICE-BINARY; do
        if [ -e "$stage/$f" ]; then cp "$stage/$f" "$d/$f"
        elif [ -e "$src/$f" ]; then cp "$src/$f" "$d/$f"; fi
    done
}
# Every program and library finds its libraries beside itself. The release tarball gets this from
# scripts/package-linux.sh's pack_localize; a stage taken from a build (or from an older package) still
# carries the build machine's RUNPATH, and in the package that path is gone - which is exactly how a
# dev-built llama-server came to ship unable to load libllama-server-impl.so beside it (#549, measured
# in the v2 VM). Entries that are not the build machine's home (a packaged /opt) are kept.
localize() {   # <tree>
    local f rp kept
    while IFS= read -r f; do
        rp=$(patchelf --print-rpath "$f" 2>/dev/null) || continue
        case ":$rp:" in *:/home/*) ;; *) continue ;; esac
        kept=$(printf '%s' "$rp" | tr ':' '\n' | grep -v '^/home/' | grep -v '^$' | tr '\n' ':' | sed 's/:$//' || true)
        patchelf --set-rpath "\$ORIGIN${kept:+:$kept}" "$f"
    done <<EOF
$(find "$1" -type f -size +1k -exec sh -c 'head -c 4 "$1" | grep -q ELF && echo "$1"' _ {} \;)
EOF
    # nothing may still point into the build machine's home
    bad=$(find "$1" -type f -size +1k -exec sh -c 'head -c 4 "$1" | grep -q ELF && patchelf --print-rpath "$1"' _ {} \; |
        tr ':' '\n' | grep '^/home/' | sort -u | head -3 || true)
    [ -z "$bad" ] || { echo "mkdebs: RUNPATH into the build machine left in the package:"; echo "$bad"; exit 1; }
}

echo "== 1bit-engine"
newpkg 1bit-engine
mkdir -p "$p/opt/1bit"
cp -a "$stage"/. "$p/opt/1bit/"
mkdir -p "$p/usr/bin"
ln -sfn /opt/1bit/1bit "$p/usr/bin/1bit"
# the two commands a boot is proved with ship with the engine: they are how the release is checked
install -m 755 "$src/os/mini/selftest.sh" "$p/usr/bin/1bit-selftest"
install -m 755 "$src/os/mini/release-check.sh" "$p/usr/bin/1bit-release-check"
mkdir -p "$p/etc/1bit"
cat > "$p/etc/1bit/engine.conf" <<'CONF'
# Paths the engine and Lemonade's onebit backend read. Static, because dpkg puts them here - the
# BusyBox image had to compute them at boot (os/mini/init.sh, os/mini/mkimage.sh).
ONEBIT_HRX_SERVER=/opt/1bit/hrx/llama/bin/llama-server
GGML_HRX_JIT_CACHE_DIR=/data/cache/hrx-jit
CONF
doc "$p" 1bit-engine
if [ -n "${ENGINE_BUILD:-}" ]; then
    # the house localiser from scripts/pack-elf.sh, the one scripts/package-linux.sh uses: every program
    # and library finds its libraries beside itself, the ones it loaded from elsewhere in the build tree
    # (HRX's libhrx/libloomc, LLVM's libomp) are copied next to it, and RUNPATH becomes $ORIGIN (#549).
    # The stage has the build's layout (mkdebs copies 1bit's surface relative to 1bit), which is what
    # lets it map a packaged file back to the build it came from.
    . "$src/scripts/pack-elf.sh"
    pack_localize "$p/opt/1bit" "$(cd "$ENGINE_BUILD" && pwd)"
    patchelf --remove-rpath "$p/opt/1bit/1bit"   # the engine binary needs no search path at all
else
    # a stage with no build tree behind it (a tarball, an older package): all that can be done is to
    # stop the build machine's paths travelling; the check below catches a library left behind
    localize "$p/opt/1bit"
    echo "mkdebs: ENGINE_BUILD not given - RUNPATH rewritten to \$ORIGIN, libraries from a build tree NOT added" >&2
fi
# the sealed NPU kernel sets must be the artifacts only: plaintext layer1.work/ would leak how the
# kernels are made, so the package build refuses anything else (the same rule mkimage.sh enforces)
if [ ! -d "$p/opt/1bit/npu/kernels" ]; then
    # a release stage always carries the sealed sets (they are what makes the NPU entries run); a
    # development stage on a machine without them can still package the rest, loudly
    echo "mkdebs: WARNING - this stage carries no npu/kernels: the package ships without the sealed NPU sets" >&2
fi
if [ -d "$p/opt/1bit/npu/kernels" ]; then
    total=$(find "$p/opt/1bit/npu/kernels" -name layer1.elf | wc -l)
    sealed=$(find "$p/opt/1bit/npu/kernels" -name layer1.elf -exec sh -c 'head -c 8 "$1" | grep -q 1BPKCRYP' _ {} \; -print | wc -l)
    stray=$(find "$p/opt/1bit/npu/kernels" -mindepth 3 \( -name '*.mlir' -o -name '*.o' -o -name 'layer1.work' -o -name '*.pdi' \) | head -3)
    [ "$total" -gt 0 ] || { echo "mkdebs: the stage carries no sealed NPU kernel sets"; exit 1; }
    [ "$sealed" = "$total" ] || { echo "mkdebs: $sealed of $total kernels are sealed in the stage"; exit 1; }
    [ -z "$stray" ] || { echo "mkdebs: the stage carries build artifacts, not just layout.json + layer1.elf:"; echo "$stray"; exit 1; }
    echo "   npu/kernels: $sealed sealed kernels"
fi
# the engine's llama-server must resolve its own libraries from the package, not from a build tree
if [ -x "$p/opt/1bit/hrx/llama/bin/llama-server" ]; then
    miss=$(ldd "$p/opt/1bit/hrx/llama/bin/llama-server" 2>/dev/null | awk '/not found/ {print $1}' | tr '\n' ' ')
    [ -z "$miss" ] || { echo "mkdebs: llama-server misses libraries: $miss"; exit 1; }
fi
dpkg-deb --build --root-owner-group "$p" "$out/1bit-engine_${debver}_amd64.deb" >/dev/null

echo "== 1bit-lemonade"
newpkg 1bit-lemonade
mkdir -p "$p/opt/lemonade"
cp -a "$lemon/bin" "$p/opt/lemonade/"
localize "$p/opt/lemonade"
mkdir -p "$p/usr/lib/systemd/system"
# the unit travels with the server it starts (design §3.2), not with the meta package
install -m 644 "$here/debian/1bit-lemonade/1bit-lemonade.service" \
    "$p/usr/lib/systemd/system/1bit-lemonade.service"
mkdir -p "$p/usr/share/doc/1bit-lemonade"
# the credit line, verbatim, where the licences live: NOTICE travels with the package
cat > "$p/usr/share/doc/1bit-lemonade/NOTICE" <<'NOTICE'
1bit OS, Lemonade Server appliance

Lemonade Server by AMD, running on the 1bit engine

This package is our build of Lemonade Server (lemond, the lemonade CLI and the web app) from the
1bit fork, with the onebit recipe: the appliance's server, running the 1bit engine.
NOTICE
cp "$src/third_party/lemonade/LICENSE" "$p/usr/share/doc/1bit-lemonade/LICENSE" 2>/dev/null || true
# the HSA runtime the engine's llama-server loads, when the build prefix carries one: a package path,
# so /etc/1bit/libhsa is a file dpkg owns instead of something computed at boot (compare #542)
hsa=$(find "$lemon" -maxdepth 3 -name 'libhsa-runtime64.so*' 2>/dev/null | head -1)
if [ -n "$hsa" ]; then
    mkdir -p "$p/opt/lemonade/lib" "$p/etc/1bit"
    cp -L "$hsa" "$p/opt/lemonade/lib/libhsa-runtime64.so.1"
    printf 'IREE_HAL_AMDGPU_LIBHSA_PATH=/opt/lemonade/lib/libhsa-runtime64.so.1\n' > "$p/etc/1bit/libhsa.env"
    echo "   HSA runtime: packed at /opt/lemonade/lib/libhsa-runtime64.so.1"
fi
dpkg-deb --build --root-owner-group "$p" "$out/1bit-lemonade_${debver}_amd64.deb" >/dev/null

echo "== 1bit-appliance"
newpkg 1bit-appliance
withscripts 1bit-appliance
cp -a "$here/debian/1bit-appliance/files"/. "$p/"
# the aggregate licence set every 1bit OS image carries, in the one place 1bit-release-check looks
# (/usr/share/licenses/1bit-os): the binary licence pair, plus the component map (os/LICENSES.md)
mkdir -p "$p/usr/share/licenses/1bit-os"
for f in LICENSE NOTICE LICENSE-BINARY NOTICE-BINARY; do
    [ -e "$src/$f" ] && cp "$src/$f" "$p/usr/share/licenses/1bit-os/"
done
cp "$src/os/LICENSES.md" "$p/usr/share/licenses/1bit-os/LICENSES.md"
# identity: release-check's identity row reads this, and it names exactly what was built
mkdir -p "$p/etc/1bit"
{
    echo "edition=1bit OS, Lemonade Server appliance"
    echo "version=$version"
    echo "engine=$engine_version"
    echo "built=$(date -u +%FT%TZ)"
} > "$p/etc/1bit/release-identity"
# on a box the appliance is the kernel and the two board tools as well: with a kernel stage they are
# dependencies (apt installs the six together), without one this stays the build/VM package
if [ -n "$kver" ]; then
    sed -i "s|^Depends: \(.*\)|Depends: \1, 1bit-kernel-image-$kver (= $debver), 1bit-kernel-modules-$kver (= $debver), 1bit-ryzenadj (= $debver)|" \
        "$p/DEBIAN/control"
fi
dpkg-deb --build --root-owner-group "$p" "$out/1bit-appliance_${debver}_amd64.deb" >/dev/null

# --- the optional one: no target wants it, nothing depends on it, so an absent or failing OpenWebUI
# can never hold a boot (engine#594). It publishes like the rest, is installed by nobody, and the
# operator's `apt install 1bit-openwebui` is what a box runs it with (os/v2/README.md).
echo "== 1bit-openwebui"
newpkg 1bit-openwebui
withscripts 1bit-openwebui
cp -a "$here/debian/1bit-openwebui/files"/. "$p/"
# cp -a keeps what git has, but the modes are what systemd and dpkg will honour: say them here
chmod 755 "$p/usr/lib/1bit/openwebui-run.sh" "$p/usr/lib/1bit/openwebui-console.sh"
mkdir -p "$p/usr/share/doc/1bit-openwebui"
# the software itself is the upstream image, pulled on the box at first start: the licence travels with
# the image, so what this package carries is who it came from and where its settings are
doc "$p" 1bit-openwebui
cat > "$p/usr/share/doc/1bit-openwebui/UPSTREAM" <<'UPSTREAM'
1bit OS, the optional OpenWebUI chat front end

OpenWebUI is not distributed in this package: it is the upstream container image
(ghcr.io/open-webui/open-webui), pulled by the unit on the box at its first start, and its own licence
travels with that image. What this package carries is the unit, the console line, the environment it is
run with, and 1bit OS's Apache-2.0 licence beside this file.
UPSTREAM
builddeb

echo "== 1bit-archive-keyring"
newpkg 1bit-archive-keyring
mkdir -p "$p/usr/share/keyrings"
if [ -n "$keyring" ] && [ -s "$keyring" ]; then
    install -m 644 "$keyring" "$p/usr/share/keyrings/1bit-archive-keyring.gpg"
else
    echo "mkdebs: no archive keyring given, so 1bit-archive-keyring ships without a key" >&2
    : > "$p/usr/share/keyrings/1bit-archive-keyring.gpg"
fi
dpkg-deb --build --root-owner-group "$p" "$out/1bit-archive-keyring_${debver}_all.deb" >/dev/null

# --- the three a box needs and a VM does not: the kernel and the two board tools --------------------
if [ -n "$kstage" ]; then
    echo "== 1bit-kernel-image-$kver"
    newpkg 1bit-kernel-image
    mkdir -p "$p/boot"
    for f in vmlinuz System.map config; do install -m 644 "$kstage/boot/$f-$kver" "$p/boot/$f-$kver"; done
    withscripts 1bit-kernel-image
    mkdir -p "$p/usr/share/doc/1bit-kernel-image-$kver"
    cp /usr/share/common-licenses/GPL-2 "$p/usr/share/doc/1bit-kernel-image-$kver/copyright"
    # the signature the boot chain checks, named in the package: sbverify against the enrolled MOK
    sbverify --list "$p/boot/vmlinuz-$kver" 2>/dev/null | grep -q 'signature 1' || {
        echo "mkdebs: $kver's vmlinuz carries no signature: Secure Boot would refuse it"; exit 1; }
    builddeb

    echo "== 1bit-kernel-modules-$kver"
    newpkg 1bit-kernel-modules
    mkdir -p "$p/lib/modules" "$p/usr/share/doc/1bit-kernel-modules-$kver"
    # *.bak files are how the development box keeps the previous signed .ko; not part of a package
    cp -a "$kstage/lib/modules/$kver" "$p/lib/modules/"
    find "$p/lib/modules/$kver" -name '*.bak*' -delete
    # GPL-2: the EC driver's binary travels with the source it was built from
    mkdir -p "$p/usr/src/1bit-ec-$version"
    cp -a "$src/os/licenses/ec_su_axb35/src"/. "$p/usr/src/1bit-ec-$version/"
    cp "$src/os/licenses/ec_su_axb35/LICENSE" "$p/usr/src/1bit-ec-$version/LICENSE"
    cp /usr/share/common-licenses/GPL-2 "$p/usr/share/doc/1bit-kernel-modules-$kver/copyright"
    withscripts 1bit-kernel-modules
    builddeb

    echo "== 1bit-ryzenadj"
    newpkg 1bit-ryzenadj
    rjsrc=$src/os/licenses/ryzenadj/src
    [ -d "$rjsrc" ] || { echo "mkdebs: no $rjsrc (the pinned ryzenadj v0.19.0 source)"; exit 2; }
    # the SMU limits go through /dev/mem, which needs no root-owned helper: a userspace build, as the
    # pinned SOURCE says, and the source ships beside the binary (LGPL-3.0)
    ( cd "$work" && cp -a "$rjsrc" rj && cmake -S rj -B rj/build -DCMAKE_BUILD_TYPE=Release >/dev/null \
        && cmake --build rj/build -j4 >/dev/null ) || { echo "mkdebs: the ryzenadj build failed (needs cmake, gcc, pkg-config, libpci-dev)"; exit 1; }
    mkdir -p "$p/usr/bin" "$p/usr/share/doc/1bit-ryzenadj"
    install -m 755 "$work/rj/build/ryzenadj" "$p/usr/bin/ryzenadj"
    miss=$(ldd "$p/usr/bin/ryzenadj" 2>/dev/null | awk '/not found/ {print $1}' | tr '\n' ' ')
    [ -z "$miss" ] || { echo "mkdebs: ryzenadj misses libraries: $miss"; exit 1; }
    cp "$src/os/licenses/ryzenadj/LICENSE" "$p/usr/share/doc/1bit-ryzenadj/copyright"
    ( cd "$rjsrc" && tar --xz -cf "$p/usr/share/doc/1bit-ryzenadj/source.tar.xz" . )
    builddeb
else
    echo "mkdebs: KERNEL_STAGE not given - no 1bit-kernel-image/-modules/-ryzenadj (VM and rootfs builds need none)" >&2
fi

echo; ls -la "$out"/*.deb
